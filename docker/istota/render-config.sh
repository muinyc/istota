# Render to a sibling and move it into place, so a partial file can never be
# mistaken for a finished one.
#
# The preflight above covers four inputs; everything else that can fail does so
# *after* the first `cat >` has already truncated the destination — python3
# missing, ENOSPC, a future unguarded `${VAR}` read. Writing in place would put
# a truncated config where a working one was, and the daemon would exec on the
# fragment.
#
# Since ISSUE-368 this is also what makes a failed render *survivable*: the
# entrypoint renders on every boot, and its fallback — keep the existing config,
# say so loudly, re-render next boot — is only safe because a failure here
# cannot have touched the file that fallback returns to.
#
# The sibling rather than mktemp: `mv` is only atomic within a filesystem, and
# /tmp is a different one in most of these deployments.
config_final="$CONFIG_FILE"
config_partial="${config_final}.partial"
trap 'rm -f "$config_partial"' EXIT
CONFIG_FILE="$config_partial"

render_config

mv -f "$config_partial" "$config_final"
trap - EXIT

# Moved out of the body so it says what it means: the file is in place by the
# time this prints, which was not true when it sat at the end of the render.
echo "[istota] Config written to ${config_final}"
