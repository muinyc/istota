#!/bin/bash
# Render /data/config/config.toml for the Docker deployment.
#
# This was entrypoint.sh's `if [ ! -f "$CONFIG_FILE" ]` block, lifted out so it
# can be run without a Nextcloud to provision against. The entrypoint still owns
# the decision of *whether* to render, and since ISSUE-368 the answer is "every
# boot" — this script is the single writer of config.toml, and the three
# add-if-missing backfill passes that used to repair an existing config on an
# upgrade are gone, because a fresh render supersedes all three.
#
# It is executed, never sourced. entrypoint.sh runs `set -euo pipefail`, so a
# sourced script would inherit `-u` and abort the entire boot on any unset
# variable it happened to read. As a subprocess, a bad hand-off fails the render
# and leaves the caller free to say so.
#
# INPUTS. These are not the environment in the ordinary sense — they are shell
# locals the provisioning phase produces earlier in entrypoint.sh, exported
# across the call. The ISTOTA_* variables are the operator-facing ones from
# docker-compose.yml and carry `:-` defaults; the rest come from provisioning:
#
# Line numbers are deliberately absent — they drift on the next edit to the
# entrypoint, and this header already went stale once that way. Each name below
# is greppable in entrypoint.sh, which does not.
#
#   CONFIG_FILE     required  where to write
#   USER_NAME       required  the primary user's id
#   NC_URL          required  internal Nextcloud URL (NC_INTERNAL_URL)
#   APP_PASSWORD    required  the bot's Nextcloud app password (from BOT_PASSWORD)
#   BOT_USER                  the bot's Nextcloud login (default "istota")
#   USER_DISPLAY_NAME, USER_TIMEZONE, USER_EMAIL
#   USER_LOG_CHANNEL, USER_ALERTS_CHANNEL, USER_DISABLED_SKILLS
#   USER_DISABLED_MODULES
#   USER_MAX_FOREGROUND_WORKERS, USER_MAX_BACKGROUND_WORKERS
#   LOG_TOKEN, ALERTS_TOKEN         room tokens, from create_group_room
#   LOCATION_INGEST_TOKEN           generated by the provisioning phase
#   OAUTH_CLIENT_ID, OAUTH_CLIENT_SECRET, OAUTH_REDIRECT_URI
#   WEB_PORT
#   WEB_SESSION_SECRET              the web session signing key, resolved once
#                                   per boot by entrypoint.sh so a re-render
#                                   keeps it; a fresh one is minted here when
#                                   no caller supplies it
#   MONARCH_EMAIL, MONARCH_PASSWORD
#   ISTOTA_*                        see docker/docker-compose.yml
#
# **No backticks inside a heredoc in this file.** Every heredoc here is
# unquoted so that ${...} expands, which is the point, and a backtick pair is
# therefore a command substitution rather than the prose markup a reader writing
# a comment intends: the shell runs the words between them, says "command not
# found" on stderr, substitutes the empty string, and the script exits 0 with
# the words gone from its own output. Measured on the [talk.signaling] block,
# whose comment named two files that way and rendered with both names missing.
# `tests/test_render_config.py::TestNoHeredocRunsACommand` refuses one, and the
# render helper there requires empty stderr for the same class of defect.
#
# `tests/test_render_config.py` holds entrypoint.sh's `export` list to this
# contract, so a name added here without being exported fails a test rather than
# rendering as empty on a real boot.
#
# Two of the provisioning locals the entrypoint holds are deliberately absent:
# ROOM_TOKEN and GENERAL_TOKEN are never read by the render.
#
# The body below is the extracted block, unchanged. It sits inside a function so
# it can keep its original indentation — the heredoc bodies it contains are at
# column 0, and dedenting the surrounding shell would have meant editing 460
# lines of interleaved heredocs to save four spaces.

set -euo pipefail

# Fail before writing anything, naming every missing input. Bare `set -u` would
# abort at the first unbound read instead, part-way through the file, leaving a
# truncated config that the entrypoint's own file-exists guard then treats as
# complete on the next boot.
#
# The test is "set", not "non-empty", so this is exactly the abort `set -u` gave
# before the extraction and no deployment that rendered a config yesterday stops
# rendering one today. An empty APP_PASSWORD still produces an empty
# `app_password`, as it always did.
#
# Written out four times rather than looped over ${!name+x}: macOS ships bash
# 3.2, this file's tests run there, and indirect expansion with an operator is
# not somewhere to discover a version difference.
missing=""
[ -n "${CONFIG_FILE+x}" ] || missing="$missing CONFIG_FILE"
[ -n "${USER_NAME+x}" ] || missing="$missing USER_NAME"
[ -n "${NC_URL+x}" ] || missing="$missing NC_URL"
[ -n "${APP_PASSWORD+x}" ] || missing="$missing APP_PASSWORD"
if [ -n "$missing" ]; then
    echo "[istota] render-config.sh: missing required input(s):$missing" >&2
    exit 2
fi

# Escape a value for a TOML basic string.
#
# Every credential below is interpolated into a `"`-delimited string by a shell
# heredoc, which does no escaping of its own. A `"` in an operator's password
# therefore closes the string early and the file stops being valid TOML — while
# the render still exits 0 and prints "Config written to", so the entrypoint's
# file-exists guard treats the corrupt file as complete on every later boot and
# never regenerates it. Found by review, reproduced, and covered by
# `tests/test_render_config.py::TestQuotingSurvivesTheRender`.
#
# Backslash first: escaping it after the quote would double the backslash the
# quote-escape just introduced.
toml_escape() {
    local value="$1"
    value="${value//\\/\\\\}"
    value="${value//\"/\\\"}"
    printf '%s' "$value"
}

# Render a comma-separated operator value as a TOML array of strings.
#
# `sed 's/[^,]*/"&"/g'` did this and got three things wrong, each of which
# reaches the daemon as a fact rather than as an error. A `"` in a value closed
# the string early and produced a config that does not parse — on a first boot
# there is no config.toml.prev to fall back to, so that is a crash loop. A space
# after a comma stayed part of the name, so ` briefings` matched no module and
# silently did nothing. A trailing comma produced an empty element.
#
# Split with `case` rather than by IFS word-splitting, which would also glob:
# the value is operator-written, but it is not this function's job to decide
# whether a `*` in it was meant.
#
# Prints nothing when every element is empty, so a caller's `-n` test on the
# raw value is not the only thing deciding whether the key gets written.
toml_string_list() {
    local rest="$1" item out=""
    while [ -n "$rest" ]; do
        case "$rest" in
            *,*) item="${rest%%,*}"; rest="${rest#*,}" ;;
            *)   item="$rest"; rest="" ;;
        esac
        item="${item#"${item%%[![:space:]]*}"}"
        item="${item%"${item##*[![:space:]]}"}"
        [ -n "$item" ] || continue
        [ -n "$out" ] && out="$out, "
        out="$out\"$(toml_escape "$item")\""
    done
    # `if` rather than a trailing `&&`: this is the function's last command, so
    # under the script's `set -e` an empty list would make `x="$(...)"` abort
    # the whole render rather than assign the empty string.
    if [ -n "$out" ]; then
        printf '[%s]' "$out"
    fi
}

# The five that can carry a metacharacter: four an operator types by hand into
# docker/.env, plus the mount point, which compose supplies but an operator may
# override and which is free text on the Nextcloud side (a display name, not a
# slug). Everything else rendered into a TOML string is machine-generated hex, a
# URL, or a value from the Nextcloud API.
#
# Rewritten in place rather than into new names so the extracted body below
# stays byte-identical to what it was in entrypoint.sh. Safe because this is a
# subprocess: the escaped values die with it and never reach the daemon.
APP_PASSWORD="$(toml_escape "${APP_PASSWORD}")"
ISTOTA_EMAIL_IMAP_PASSWORD="$(toml_escape "${ISTOTA_EMAIL_IMAP_PASSWORD:-}")"
ISTOTA_DEVELOPER_GITLAB_TOKEN="$(toml_escape "${ISTOTA_DEVELOPER_GITLAB_TOKEN:-}")"
ISTOTA_DEVELOPER_GITHUB_TOKEN="$(toml_escape "${ISTOTA_DEVELOPER_GITHUB_TOKEN:-}")"
ISTOTA_NEXTCLOUD_DAV_PREFIX="$(toml_escape "${ISTOTA_NEXTCLOUD_DAV_PREFIX:-}")"

render_config() {
    echo "[istota] Generating config.toml..."

    DISPLAY_NAME="${USER_DISPLAY_NAME:-$USER_NAME}"
    TIMEZONE="${USER_TIMEZONE:-UTC}"

    cat > "$CONFIG_FILE" <<TOML
# Istota configuration — generated by Docker entrypoint

bot_name = "${ISTOTA_BOT_NAME:-Istota}"
emissaries_enabled = ${ISTOTA_EMISSARIES_ENABLED:-true}

db_path = "/data/db/istota.db"
nextcloud_mount_path = "/mnt/shared"
skills_dir = "/app/config/skills"
temp_dir = "/data/tmp"
max_memory_chars = ${ISTOTA_MAX_MEMORY_CHARS:-0}
TOML

    # No top-level `model` key any more. It was the claude_code brain's own
    # default living at the root, where the executor applied it to whatever
    # brain ran and it shadowed that brain's configured default (ISSUE-418).
    # ISTOTA_MODEL still works and is migrated onto the per-brain keys by the
    # [brain.claude_code] / [brain.tmux] render below — done here rather than by
    # the loader's deprecation path so a Docker deployment that never changes
    # its .env stops warning at every boot. The generator is what a generated
    # config is for.

    # Disabled skills (optional). Through `toml_string_list` like every other
    # comma-separated value here: this one is deployment-wide, so a `"` in it
    # breaks the whole config rather than one user's key.
    _disabled_skills_list="$(toml_string_list "${ISTOTA_DISABLED_SKILLS:-}")"
    if [ -n "$_disabled_skills_list" ]; then
        echo "disabled_skills = $_disabled_skills_list" >> "$CONFIG_FILE"
    fi

    # Experimental features (operator opt-in for rough, off-by-default work).
    # Comma-separated, e.g. "money_tax,money_wash_sales". See docs/EXPERIMENTAL.md.
    cat >> "$CONFIG_FILE" <<TOML

[experimental]
TOML
    _experimental_list="$(toml_string_list "${ISTOTA_EXPERIMENTAL_FEATURES:-}")"
    if [ -n "$_experimental_list" ]; then
        echo "features = $_experimental_list" >> "$CONFIG_FILE"
    else
        echo "features = []" >> "$CONFIG_FILE"
    fi

    # Brain (model backend). kind=claude_code (default) shells out to the
    # Claude CLI; kind=native runs the in-process agent loop; kind=tmux_claude
    # drives the interactive TUI via tmux. The native provider API key is read
    # from ISTOTA_BRAIN_NATIVE_API_KEY at load time, so it is deliberately not
    # written into config.toml.
    #
    # Brain fallback (availability failover): when the primary brain is
    # unavailable (usage limit / missing binary / tmux launch failure), rerun the
    # task on ISTOTA_BRAIN_FALLBACK with that brain's own settings. "" = none,
    # whatever the primary kind (ISSUE-362) — except that an unset value on a
    # tmux_claude primary is filled in with claude_code below.
    cat >> "$CONFIG_FILE" <<TOML

[brain]
kind = "${ISTOTA_BRAIN_KIND:-claude_code}"
fallback_on_transient = ${ISTOTA_BRAIN_FALLBACK_ON_TRANSIENT:-false}
fallback_cooldown_seconds = ${ISTOTA_BRAIN_FALLBACK_COOLDOWN_SECONDS:-900}
TOML
    # Which brain kinds a room may pin for itself, and which a scheduled job may
    # pin with `brain` in CRON.md -- one list bounds every pin written outside
    # this file, so the key's name is narrower than the setting. Comma-separated,
    # empty by default, so both are off until an operator names kinds.
    # Rendered only when at least one name survives: an empty list and an absent
    # key load identically, and this file is rewritten on every boot, so a key
    # printed at its own default invites editing a generated file.
    #
    # Each name goes through `toml_escape`, for the reason every operator-typed
    # value here does -- a `"` would otherwise close the string early and leave a
    # config.toml that does not parse, which on this shape is a container that
    # will not boot. Nothing here judges whether a name is a real brain kind:
    # `config._validate_room_selectable` warns once at load about a name
    # `make_brain` cannot build, and a second opinion in a shell script would
    # only go out of date when a fourth kind ships.
    #
    # Every branch is an explicit `if`. `set -e` is in force, and the idiomatic
    # `[ -z "$x" ] && continue` exits the whole render whenever the test is
    # false -- which is the ordinary case, so it would fail every boot that set
    # this variable.
    if [ -n "${ISTOTA_BRAIN_ROOM_SELECTABLE:-}" ]; then
        _room_selectable=""
        _IFS_SAVED="$IFS"
        IFS=','
        for _kind in $ISTOTA_BRAIN_ROOM_SELECTABLE; do
            _kind="$(echo "$_kind" | tr -d '[:space:]')"
            if [ -z "$_kind" ]; then
                continue
            fi
            if [ -n "$_room_selectable" ]; then
                _room_selectable="${_room_selectable}, "
            fi
            _room_selectable="${_room_selectable}\"$(toml_escape "$_kind")\""
        done
        IFS="$_IFS_SAVED"
        if [ -n "$_room_selectable" ]; then
            echo "room_selectable = [${_room_selectable}]" >> "$CONFIG_FILE"
        fi
    fi

    # A tmux_claude primary with nothing set gets claude_code written in, which
    # is the failover it had implicitly before ISSUE-362 — same default the
    # Ansible role applies, so the two deployment shapes agree. Setting
    # ISTOTA_BRAIN_FALLBACK to any other value, including a single space, wins.
    # Since ISSUE-368 this reaches every boot rather than the first alone, so a
    # tmux deployment provisioned before ISSUE-362 gets the key on its next
    # restart instead of only learning from the config-load INFO line that it
    # has no failover.
    _brain_fallback="${ISTOTA_BRAIN_FALLBACK:-}"
    if [ -z "$_brain_fallback" ] \
        && [ "${ISTOTA_BRAIN_KIND:-claude_code}" = "tmux_claude" ]; then
        _brain_fallback="claude_code"
    fi
    if [ -n "$_brain_fallback" ]; then
        echo "fallback = \"${_brain_fallback}\"" >> "$CONFIG_FILE"
    fi

    # Each CLI brain's own default model / effort (ISSUE-418). Both blocks are
    # rendered whatever `kind` is, unlike [brain.native] below, because both are
    # read whatever it is: a native primary with a claude_code fallback, or a
    # source_type_overrides entry, runs the other brain and needs its default.
    #
    # ISTOTA_MODEL is the legacy spelling and feeds both, which is what makes
    # the migration exactly behaviour-preserving: it *was* the default for
    # whichever CLI brain ran, and the two share the anthropic namespace and the
    # same binary, so the value is equally valid in either. It is deliberately
    # not fed to [brain.native] — a value written in the Anthropic vocabulary
    # cannot carry to an openai_compat endpoint, which is the defect itself.
    #
    # A section header is written only when the block has a key to hold, so an
    # unconfigured deployment renders neither and loads the dataclass defaults.
    _cc_model="${ISTOTA_BRAIN_CLAUDE_CODE_MODEL:-${ISTOTA_MODEL:-}}"
    _cc_effort="${ISTOTA_BRAIN_CLAUDE_CODE_EFFORT:-}"
    if [ -n "$_cc_model" ] || [ -n "$_cc_effort" ]; then
        echo "" >> "$CONFIG_FILE"
        echo "[brain.claude_code]" >> "$CONFIG_FILE"
        if [ -n "$_cc_model" ]; then
            echo "model = \"$(toml_escape "$_cc_model")\"" >> "$CONFIG_FILE"
        fi
        if [ -n "$_cc_effort" ]; then
            echo "effort = \"$(toml_escape "$_cc_effort")\"" >> "$CONFIG_FILE"
        fi
    fi
    # [brain.tmux]'s own model/effort are emitted with the rest of that block
    # further down, not here: this file already writes a `[brain.tmux]` header
    # for the tmux kind, and a second one is a duplicate table — invalid TOML,
    # which on this shape is a container that will not boot.
    if [ "${ISTOTA_BRAIN_KIND:-claude_code}" = "native" ]; then
        cat >> "$CONFIG_FILE" <<TOML

[brain.native]
provider = "${ISTOTA_BRAIN_NATIVE_PROVIDER:-openai_compat}"
base_url = "${ISTOTA_BRAIN_NATIVE_BASE_URL:-https://api.anthropic.com/v1}"
context_window = ${ISTOTA_BRAIN_NATIVE_CONTEXT_WINDOW:-0}
max_turns = ${ISTOTA_BRAIN_NATIVE_MAX_TURNS:-100}
max_tokens = ${ISTOTA_BRAIN_NATIVE_MAX_TOKENS:-16384}
TOML
        # Scalar [brain.native] keys (effort, model, prompt_caching) must
        # precede the [brain.native.web_fetch] subtable and the [models.roles]
        # table below, or TOML would attach them to the wrong table.
        #
        # prompt_caching is tri-state and the empty value is *not* false: the
        # dataclass default is None, which llm/__init__.py reads as "on for
        # api.anthropic.com, off elsewhere". So the key is omitted unless the
        # operator forced one, the way the Ansible template already does it —
        # rendering `false` unconditionally, which this file did until
        # ISSUE-430, turned caching off on the default Anthropic deployment and
        # paid full uncached input every turn. Anything that is not true/false
        # is dropped rather than written, since a bare word here is invalid
        # TOML and on this shape that is a container that will not boot.
        case "$(printf '%s' "${ISTOTA_BRAIN_NATIVE_PROMPT_CACHING:-}" | tr '[:upper:]' '[:lower:]')" in
            true)  echo "prompt_caching = true" >> "$CONFIG_FILE" ;;
            false) echo "prompt_caching = false" >> "$CONFIG_FILE" ;;
            "")    : ;;
            *)     echo "[istota] WARNING: ignoring ISTOTA_BRAIN_NATIVE_PROMPT_CACHING (expected true or false)" >&2 ;;
        esac
        if [ -n "${ISTOTA_BRAIN_NATIVE_EFFORT:-}" ]; then
            echo "effort = \"${ISTOTA_BRAIN_NATIVE_EFFORT}\"" >> "$CONFIG_FILE"
        fi
        if [ -n "${ISTOTA_BRAIN_NATIVE_MODEL:-}" ]; then
            echo "model = \"${ISTOTA_BRAIN_NATIVE_MODEL}\"" >> "$CONFIG_FILE"
        fi
        # Daemon-side WebFetch tool (native-only, SSRF-hardened). Safe defaults;
        # only enabled / allow_http commonly change.
        cat >> "$CONFIG_FILE" <<TOML

[brain.native.web_fetch]
enabled = ${ISTOTA_BRAIN_NATIVE_WEB_FETCH_ENABLED:-true}
allow_http = ${ISTOTA_BRAIN_NATIVE_WEB_FETCH_ALLOW_HTTP:-false}
require_url_provenance = ${ISTOTA_BRAIN_NATIVE_WEB_FETCH_REQUIRE_URL_PROVENANCE:-false}
TOML
        if [ -n "${ISTOTA_BRAIN_NATIVE_MODEL:-}" ]; then
            # Internal subsystems (conversation selection, sleep-cycle
            # extraction, OCR, …) request models by ROLE — "fast" / "general" /
            # "smart". The claude_code brain maps those to Haiku/Sonnet/Opus.
            # A native brain speaks to one endpoint, so an unmapped role
            # already falls back to the single configured model; what this
            # table buys is pointing one role somewhere else. Set
            # ISTOTA_BRAIN_NATIVE_MODEL_{FAST,GENERAL,SMART} to aim a role at a
            # different model served by the same endpoint.
            #
            # The key is [models.aliases]. [models.roles] is a hard rename that
            # config.py parses into nothing — writing it dropped every override
            # here and logged a migration warning on every process start.
            cat >> "$CONFIG_FILE" <<TOML

[models.aliases]
fast = "${ISTOTA_BRAIN_NATIVE_MODEL_FAST:-$ISTOTA_BRAIN_NATIVE_MODEL}"
general = "${ISTOTA_BRAIN_NATIVE_MODEL_GENERAL:-$ISTOTA_BRAIN_NATIVE_MODEL}"
smart = "${ISTOTA_BRAIN_NATIVE_MODEL_SMART:-$ISTOTA_BRAIN_NATIVE_MODEL}"
TOML
        fi
    fi

    # Tmux-driven interactive-TUI brain (subscription billing). The operability
    # knobs are emitted only when the kind is selected; all of them default in
    # code to the prototype's pinned values.
    #
    # The block itself is also emitted when only this brain's own model/effort
    # are set (ISSUE-418), because those are read whatever `kind` is — a
    # claude_code primary with a tmux fallback, or a source_type_overrides entry,
    # runs this brain and needs its default. One header either way: this file
    # writes `[brain.tmux]` exactly once, since a duplicate table is invalid TOML
    # and on this shape that is a container that will not boot.
    _tmux_model="${ISTOTA_BRAIN_TMUX_MODEL:-${ISTOTA_MODEL:-}}"
    _tmux_effort="${ISTOTA_BRAIN_TMUX_EFFORT:-}"
    if [ "${ISTOTA_BRAIN_KIND:-claude_code}" = "tmux_claude" ] \
        || [ -n "$_tmux_model" ] || [ -n "$_tmux_effort" ]; then
        echo "" >> "$CONFIG_FILE"
        echo "[brain.tmux]" >> "$CONFIG_FILE"
        if [ -n "$_tmux_model" ]; then
            echo "model = \"$(toml_escape "$_tmux_model")\"" >> "$CONFIG_FILE"
        fi
        if [ -n "$_tmux_effort" ]; then
            echo "effort = \"$(toml_escape "$_tmux_effort")\"" >> "$CONFIG_FILE"
        fi
    fi
    if [ "${ISTOTA_BRAIN_KIND:-claude_code}" = "tmux_claude" ]; then
        cat >> "$CONFIG_FILE" <<TOML
fallback_trip_threshold = ${ISTOTA_BRAIN_TMUX_FALLBACK_TRIP_THRESHOLD:-5}
fallback_cooldown_seconds = ${ISTOTA_BRAIN_TMUX_FALLBACK_COOLDOWN_SECONDS:-300}
ready_timeout_seconds = ${ISTOTA_BRAIN_TMUX_READY_TIMEOUT_SECONDS:-30}
cli_version_pin = "${ISTOTA_BRAIN_TMUX_CLI_VERSION_PIN:-2.1.168}"
TOML
    fi

    cat >> "$CONFIG_FILE" <<TOML

[security]
sandbox_enabled = ${ISTOTA_SECURITY_SANDBOX_ENABLED:-true}
skill_proxy_enabled = ${ISTOTA_SECURITY_SKILL_PROXY_ENABLED:-true}
skill_proxy_timeout = ${ISTOTA_SECURITY_SKILL_PROXY_TIMEOUT:-300}
sandbox_cache_dir = "${ISTOTA_SECURITY_SANDBOX_CACHE_DIR:-}"

[security.network]
enabled = false

[nextcloud]
url = "${NC_URL}"
username = "${BOT_USER:-istota}"
app_password = "${APP_PASSWORD}"
# Where /mnt/shared sits inside the bot's own Nextcloud file tree. On this shape
# it is a files_external mount, so a logical /Users/x is /<mount>/Users/x over
# DAV and OCS; compose passes the mount point provision-nc.sh created. Empty is
# the bare-metal shape, where the rclone mount *is* the bot's tree.
dav_prefix = "${ISTOTA_NEXTCLOUD_DAV_PREFIX:-}"
# The boot-time OCS share of the bot workspace back to the user. Off on this
# shape: provision-nc.sh already mounts that directory into the user's tree, so
# the share would hand them a second copy of it.
auto_share_bot_dir = ${ISTOTA_NEXTCLOUD_AUTO_SHARE_BOT_DIR:-true}

[talk]
enabled = ${ISTOTA_TALK_ENABLED:-true}
bot_username = "${BOT_USER:-istota}"

# Inbound Talk over the standalone signaling server (the "high-performance
# backend"). Off unless the operator runs one: docker-compose.yml ships the
# container behind the signaling compose profile, and a deployment without it
# keeps the poll loop, which is the capability floor rather than a fallback.
#
# There is no credential here, and the absence is the design. istota
# authenticates to the signaling server as its own Nextcloud user, so the HPB
# URL, the hello token and the per-room Talk session id are all minted on demand
# by Talk. The protocol's other door — an internal client holding the server's
# shared secret — joins any room on the instance and is rejected for that
# reason, so there is nothing to render, redact or vault.
#
# An empty url means "read the server address from Talk's own signaling
# settings". Set it where the daemon must reach the HPB by a different route
# than the one Nextcloud advertises to browsers — which is exactly the shape of
# a compose deployment, where Talk hands out the public URL and the daemon is on
# the container network beside the server.
[talk.signaling]
enabled = ${ISTOTA_TALK_SIGNALING_ENABLED:-false}
url = "${ISTOTA_TALK_SIGNALING_URL:-}"
room_sync_interval = ${ISTOTA_TALK_SIGNALING_ROOM_SYNC_INTERVAL:-300}
reconnect_backoff_max = ${ISTOTA_TALK_SIGNALING_RECONNECT_BACKOFF_MAX:-60}
payload_direct = ${ISTOTA_TALK_SIGNALING_PAYLOAD_DIRECT:-false}

[email]
enabled = ${ISTOTA_EMAIL_ENABLED:-false}
TOML

    if [ "${ISTOTA_EMAIL_ENABLED:-false}" = "true" ]; then
        cat >> "$CONFIG_FILE" <<TOML
imap_host = "${ISTOTA_EMAIL_IMAP_HOST:-}"
imap_port = ${ISTOTA_EMAIL_IMAP_PORT:-993}
imap_user = "${ISTOTA_EMAIL_IMAP_USER:-}"
imap_password = "${ISTOTA_EMAIL_IMAP_PASSWORD:-}"
smtp_host = "${ISTOTA_EMAIL_SMTP_HOST:-}"
smtp_port = ${ISTOTA_EMAIL_SMTP_PORT:-587}
poll_folder = "${ISTOTA_EMAIL_POLL_FOLDER:-INBOX}"
bot_email = "${ISTOTA_EMAIL_BOT_ADDRESS:-}"
authserv_id = "${ISTOTA_EMAIL_AUTHSERV_ID:-}"
confirm_sender_match = "${ISTOTA_EMAIL_CONFIRM_SENDER_MATCH:-off}"
outbound_approval_floor = "${ISTOTA_EMAIL_OUTBOUND_APPROVAL_FLOOR:-untrusted}"
TOML
    fi

    cat >> "$CONFIG_FILE" <<TOML

[conversation]
enabled = ${ISTOTA_CONVERSATION_ENABLED:-true}
lookback_count = ${ISTOTA_CONVERSATION_LOOKBACK_COUNT:-25}
selection_model = "${ISTOTA_CONVERSATION_SELECTION_MODEL:-fast}"
selection_timeout = ${ISTOTA_CONVERSATION_SELECTION_TIMEOUT:-30.0}
skip_selection_threshold = ${ISTOTA_CONVERSATION_SKIP_SELECTION_THRESHOLD:-3}
use_selection = ${ISTOTA_CONVERSATION_USE_SELECTION:-true}
